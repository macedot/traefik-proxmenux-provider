func parseYAML(t *testing.T, data []byte) map[string]any {
	t.Helper()
	var m map[string]any
	if err := yaml.Unmarshal(data, &m); err != nil {
		t.Fatalf("rendered YAML does not parse: %v\n%s", err, data)
	}
	return m
}

func TestRenderInternalMode(t *testing.T) {
	c := cfg(t, "")
	out, err := Render(routes(), c)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.HasPrefix(string(out), "# GENERATED by traefik-proxmenux-provider") {
		t.Error("output missing GENERATED header")
	}
	m := parseYAML(t, out)
	http := m["http"].(map[string]any)

	r := http["routers"].(map[string]any)["pmp-adguard-home"].(map[string]any)
	if r["rule"] != "Host(`adguard-home.home.example.com`)" {
		t.Errorf("rule = %v", r["rule"])
	}
	if r["service"] != "pmp-adguard-home" {
		t.Errorf("service = %v", r["service"])
	}
	if _, ok := r["tls"].(map[string]any); !ok {
		t.Errorf("router tls block missing (internal mode still needs tls: {}): %v", r)
	}
	svc := http["services"].(map[string]any)["pmp-adguard-home"].(map[string]any)
	lb := svc["loadBalancer"].(map[string]any)
	servers := lb["servers"].([]any)
	if servers[0].(map[string]any)["url"] != "http://192.0.2.2:3000" {
		t.Errorf("server url = %v", servers[0])
	}
}

