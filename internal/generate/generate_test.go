func TestRenderDashboards(t *testing.T) {
	c := cfg(t, "dashboard:\n  enabled: true\n  listen: \":8081\"\n  via_traefik: true\n  hostname: provider\n  allow_cidrs: [\"192.0.2.0/25\"]\nexpose:\n  dashboard:\n    enabled: true\n    hostname: traefik\n    allow_cidrs: [\"192.0.2.0/25\"]\n")
	out, err := Render(routes(), c)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	m := parseYAML(t, out)
	http := m["http"].(map[string]any)

	dr := http["routers"].(map[string]any)["pmp-dashboard"].(map[string]any)
	if dr["rule"] != "Host(`provider.home.example.com`)" {
		t.Errorf("dashboard rule = %v", dr["rule"])
	}
	mws := dr["middlewares"].([]any)
	if len(mws) == 0 || mws[0] != "pmp-dashboard-allowlist" {
		t.Errorf("dashboard middlewares = %v", mws)
	}
	mid := http["middlewares"].(map[string]any)["pmp-dashboard-allowlist"].(map[string]any)
	sr := mid["ipAllowList"].(map[string]any)["sourceRange"].([]any)
	if sr[0] != "192.0.2.0/25" {
		t.Errorf("sourceRange = %v", sr)
	}
	ds := http["services"].(map[string]any)["pmp-dashboard"].(map[string]any)
	url := ds["loadBalancer"].(map[string]any)["servers"].([]any)[0].(map[string]any)["url"]
	if url != "http://127.0.0.1:8081" {
		t.Errorf("dashboard service url = %v", url)
	}

	tr := http["routers"].(map[string]any)["pmp-traefik-dashboard"].(map[string]any)
	if tr["service"] != "api@internal" {
		t.Errorf("traefik dashboard service = %v", tr["service"])
	}
}

