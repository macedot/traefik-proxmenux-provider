// Package generate renders the Traefik file-provider dynamic configuration
// and writes it atomically: tmp file in the same directory, fsync, rename,
// previous copy kept as .bak. Only ever touches its own output file.
package generate

import (
	"bytes"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/macedot/traefik-proxmenux-provider/internal/config"
	"github.com/macedot/traefik-proxmenux-provider/internal/transform"
)

const header = "# GENERATED by traefik-proxmenux-provider — do not edit.\n" +
	"# This file is rewritten on every sync; changes here will be lost.\n"

// --- Traefik dynamic config model (file-provider YAML) ---

type dynConfig struct {
	HTTP *dynHTTP `yaml:"http,omitempty"`
	TLS  *dynTLS  `yaml:"tls,omitempty"`
}

type dynHTTP struct {
	Routers           map[string]*dynRouter           `yaml:"routers,omitempty"`
	Middlewares       map[string]*dynMiddleware       `yaml:"middlewares,omitempty"`
	Services          map[string]*dynServiceFallback  `yaml:"services,omitempty"`
	ServersTransports map[string]*dynServersTransport `yaml:"serversTransports,omitempty"`
}

type dynRouter struct {
	Rule        string        `yaml:"rule"`
	EntryPoints []string      `yaml:"entryPoints,omitempty"`
	Service     string        `yaml:"service,omitempty"`
	Middlewares []string      `yaml:"middlewares,omitempty"`
	TLS         *dynRouterTLS `yaml:"tls,omitempty"`
}

type dynRouterTLS struct {
	CertResolver string       `yaml:"certResolver,omitempty"`
	Domains      []domainPair `yaml:"domains,omitempty"`
}

type domainPair struct {
	Main string   `yaml:"main,omitempty"`
	Sans []string `yaml:"sans,omitempty"`
}

type dynMiddleware struct {
	IPAllowList *dynIPAllowList `yaml:"ipAllowList,omitempty"`
}

type dynIPAllowList struct {
	SourceRange []string `yaml:"sourceRange,omitempty"`
}

type dynServiceFallback struct {
	LoadBalancer *dynLB `yaml:"loadBalancer,omitempty"`
}

type dynLB struct {
	Servers          []dynServer `yaml:"servers,omitempty"`
	HealthCheck      *dynHealth  `yaml:"healthCheck,omitempty"`
	PassHostHeader   *bool       `yaml:"passHostHeader,omitempty"`
	ServersTransport string      `yaml:"serversTransport,omitempty"`
}

type dynServer struct {
	URL string `yaml:"url"`
}

type dynHealth struct {
	Path     string `yaml:"path,omitempty"`
	Interval string `yaml:"interval,omitempty"`
	Timeout  string `yaml:"timeout,omitempty"`
}

type dynServersTransport struct {
	InsecureSkipVerify bool `yaml:"insecureSkipVerify"`
}

type dynTLSCertificates struct {
	Certificates []dynCertificate `yaml:"certificates,omitempty"`
}

type dynCertificate struct {
	CertResolver string       `yaml:"certResolver"`
	Domains      []domainPair `yaml:"domains"`
}

type dynTLS = dynTLSCertificates

// routerTLS builds the per-router TLS block according to the TLS mode.
func routerTLS(cfg *config.Config) *dynRouterTLS {
	switch cfg.TLS.Mode {
	case "per-app":
		return &dynRouterTLS{CertResolver: cfg.TLS.CertResolver}
	case "wildcard":
		// Certificate comes from the global block; router just enables TLS.
		fallthrough
	default: // internal: Traefik default (self-signed) CA
		return &dynRouterTLS{}
	}
}

func allowlistMiddleware(name string, cidrs []string, m map[string]*dynMiddleware) []string {
	if len(cidrs) == 0 {
		return nil // caller must fail closed when an allowlist is required
	}
	m[name] = &dynMiddleware{IPAllowList: &dynIPAllowList{SourceRange: cidrs}}
	return []string{name}
}

// Render builds the dynamic configuration bytes from routes + config.
func Render(routes []transform.Route, cfg *config.Config) ([]byte, error) {
	d := &dynConfig{HTTP: &dynHTTP{
		Routers:     map[string]*dynRouter{},
		Middlewares: map[string]*dynMiddleware{},
		Services:    map[string]*dynServiceFallback{},
	}}
	ep := cfg.Routing.Entrypoint

	for _, r := range routes {
		if !r.Served {
			continue // stale/disabled: tagged, visible on the dashboard, never served
		}
		svcName := "pmp-" + r.Slug
		svc := &dynServiceFallback{LoadBalancer: &dynLB{
			Servers: []dynServer{{URL: r.Target}},
		}}
		if r.Insecure {
			svc.LoadBalancer.ServersTransport = "pmp-insecure"
			if d.HTTP.ServersTransports == nil {
				d.HTTP.ServersTransports = map[string]*dynServersTransport{}
			}
			d.HTTP.ServersTransports["pmp-insecure"] = &dynServersTransport{InsecureSkipVerify: true}
		}
		if cfg.Routing.HealthCheck && r.HealthPath != "" {
			svc.LoadBalancer.HealthCheck = &dynHealth{
				Path: r.HealthPath, Interval: "30s", Timeout: "5s",
			}
		}
		d.HTTP.Services[svcName] = svc

		router := &dynRouter{
			Rule:        "Host(`" + r.Hostname + "`)",
			EntryPoints: []string{ep},
			Service:     svcName,
			TLS:         routerTLS(cfg),
		}
		router.Middlewares = append(router.Middlewares, cfg.Routing.Middlewares...)
		d.HTTP.Routers[svcName] = router
	}

	// Provider dashboard routed through Traefik. FAIL-CLOSED: the UI carries
	// mutation endpoints, so it is never published without an explicit
	// allowlist — an open route would expose rename/toggle APIs publicly.
	if cfg.Dashboard.Enabled && cfg.Dashboard.ViaTraefik {
		if len(cfg.Dashboard.AllowCIDRs) == 0 {
			return nil, fmt.Errorf("dashboard.via_traefik requires dashboard.allow_cidrs " +
				"(refusing to publish the dashboard — its edit API would be public)")
		}
		port, err := listenPort(cfg.Dashboard.Listen)
		if err != nil {
			return nil, fmt.Errorf("dashboard.listen: %w", err)
		}
		mws := allowlistMiddleware("pmp-dashboard-allowlist", cfg.Dashboard.AllowCIDRs, d.HTTP.Middlewares)
		name := "pmp-dashboard"
		d.HTTP.Routers[name] = &dynRouter{
			Rule:        "Host(`" + cfg.Dashboard.Hostname + "." + cfg.Domain.Base + "`)",
			EntryPoints: []string{ep},
			Service:     name,
			Middlewares: mws,
			TLS:         routerTLS(cfg),
		}
		d.HTTP.Services[name] = &dynServiceFallback{LoadBalancer: &dynLB{
			Servers: []dynServer{{URL: "http://127.0.0.1:" + strconv.Itoa(port)}},
		}}
	}

	// Traefik's own dashboard (secure replacement for api.insecure).
	if cfg.Expose.TraefikDashboard.Enabled {
		mws := allowlistMiddleware("pmp-traefik-allowlist", cfg.Expose.TraefikDashboard.AllowCIDRs, d.HTTP.Middlewares)
		name := "pmp-traefik-dashboard"
		d.HTTP.Routers[name] = &dynRouter{
			Rule:        "Host(`" + cfg.Expose.TraefikDashboard.Hostname + "." + cfg.Domain.Base + "`)",
			EntryPoints: []string{ep},
			Service:     "api@internal",
			Middlewares: mws,
			TLS:         routerTLS(cfg),
		}
	}

	// Wildcard certificate block.
	if cfg.TLS.Mode == "wildcard" {
		d.TLS = &dynTLS{Certificates: []dynCertificate{{
			CertResolver: cfg.TLS.CertResolver,
			Domains: []domainPair{{
				Main: cfg.Domain.Base,
				Sans: []string{"*." + cfg.Domain.Base},
			}},
		}}}
	}

	var buf bytes.Buffer
	out, err := yaml.Marshal(d)
	if err != nil {
		return nil, fmt.Errorf("marshal dynamic config: %w", err)
	}
	_, _ = buf.WriteString(header)
	_, _ = buf.Write(out)
	return buf.Bytes(), nil
}

func listenPort(listen string) (int, error) {
	_, portStr, err := net.SplitHostPort(listen)
	if err != nil {
		return 0, err
	}
	port, err := strconv.Atoi(portStr)
	if err != nil || port < 1 || port > 65535 {
		return 0, fmt.Errorf("invalid port %q", portStr)
	}
	return port, nil
}

// WriteAtomic writes data to path atomically. Returns whether the file
// changed. Never touches anything besides path and path+".bak".
func WriteAtomic(path string, mode os.FileMode, backup bool, data []byte) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) { // #nosec G304 -- output path from admin-controlled config
		return false, nil
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return false, fmt.Errorf("create output dir: %w", err)
	}
	if backup {
		if old, err := os.ReadFile(path); err == nil { // #nosec G304 -- output path from admin-controlled config
			if err := os.WriteFile(path+".bak", old, mode); err != nil { // #nosec G703 -- derived from the same admin-controlled path
				return false, fmt.Errorf("write backup: %w", err)
			}
		}
	}
	tmp, err := os.CreateTemp(dir, ".pmp-generated-*")
	if err != nil {
		return false, fmt.Errorf("create temp file: %w", err)
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }() // no-op after successful rename

	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return false, fmt.Errorf("chmod temp file: %w", err)
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return false, fmt.Errorf("write temp file: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return false, fmt.Errorf("fsync temp file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return false, fmt.Errorf("close temp file: %w", err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return false, fmt.Errorf("rename into place: %w", err)
	}
	return true, nil
}

// SanitizeHostname is used by the installer/docs; kept here for reuse.
func SanitizeHostname(h string) string {
	return strings.ToLower(strings.TrimSpace(h))
}
